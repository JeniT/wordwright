function declarations(tokens) {
  return Object.entries(tokens)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join('\n')
}

function tokensCss(id) {
  const { light, dark } = themes[id].modes
  let css = `/* Generated by tools/build.mjs from tools/tokens.mjs. Do not edit by hand. */\n:root {\n${declarations(light)}\n}\n`
  if (dark) {
    css += `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n${declarations(dark).replace(/^/gm, '  ')}\n  }\n}\n`
    css += `:root[data-theme='dark'] {\n${declarations(dark)}\n}\n`
  }
  return css
}

